marker="## 환자 관점에서 먼저 구분하기"

for rel,info in pages.items():
    p=docs/rel
    if not p.exists():
        print("SKIP:",rel)
        continue
    t=p.read_text(encoding="utf-8")
    block = marker + "\n\n"
    block += "### 이런 질문으로 들어올 수 있습니다\n\n" + "\n".join(f"- {x}" for x in info["queries"]) + "\n\n"
    block += "### 이런 원인·상태를 함께 구분합니다\n\n" + "\n".join(f"- {x}" for x in info["could"]) + "\n\n"
    block += "### 먼저 확인해야 할 신호\n\n" + "\n".join(f"- {x}" for x in info["red"]) + "\n\n"
    block += "### 한의치료는 이렇게 연결합니다\n\n" + info["tx"] + "\n\n"
    block += "**핵심:** 같은 증상 표현이라도 원인이 하나가 아니므로, 검색어만으로 처방을 정하지 않고 감별 → 병증 → 치료 순으로 봅니다.\n"
    if marker in t:
        t=t.split(marker,1)[0].rstrip()+"\n\n"+block
    else:
        t=t.rstrip()+"\n\n"+block
    p.write_text(t,encoding="utf-8")
    print("UPDATED:",rel)

