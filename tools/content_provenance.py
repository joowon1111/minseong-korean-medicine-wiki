"""Public provenance, not DRM: stable IDs, reproducible digests and SVG branding.

Runs after page_discovery so navigation/citation chrome never enters the digest.
No visitor IDs, browser telemetry, hidden text or external requests are added.
"""
from hashlib import sha256
from html import escape
import json
from pathlib import Path
import re
import subprocess
import unicodedata
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = 'https://github.com/joowon1111/minseong-korean-medicine-wiki'
MANIFEST = 'assets/provenance/manifest.json'
# Original artwork generated by this repository. External images/3D models stay untouched.
ARTWORK = ('acupoint-atlas', 'learning/diagrams', 'learning/anatomy-diagrams',
           'tung-atlas', 'mps-atlas', 'acupuncture-science', 'rehab', 'dermatomes')
_documents = {}
_revision = {}


def normalize_text(text):
    return re.sub(r'\s+', ' ', unicodedata.normalize('NFC', text)).strip()


def digest(text):
    return sha256(normalize_text(text).encode('utf-8')).hexdigest()


def document_id(url):
    return 'MSA-' + sha256(url.encode('utf-8')).hexdigest()[:16].upper()


def search_samples(text):
    """Public prose excerpts for rotating exact-phrase searches, never canary facts."""
    candidates = []
    for line in text.splitlines():
        if '\t' in line:
            continue
        line = normalize_text(line)
        if 90 <= len(line) <= 1500 and not re.search(r'https?://|[<>]|\t', line):
            sample = line[:110]
            if sample not in candidates:
                candidates.append(sample)
    if len(candidates) <= 3:
        return candidates
    return [candidates[i] for i in (0, len(candidates)//2, len(candidates)-1)]


def on_pre_build(config):
    _documents.clear()
    _revision.clear()
    # A repository commit is a version reference, not an independent timestamp/notarization.
    try:
        commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
        committed_at = subprocess.check_output(['git', 'show', '-s', '--format=%cI', 'HEAD'], cwd=ROOT, text=True).strip()
        if re.fullmatch('[0-9a-f]{40}', commit):
            _revision.update(commit=commit, committed_at=committed_at)
    except (OSError, subprocess.CalledProcessError):
        pass


def on_page_content(html, page, config, files):
    discovery = getattr(page, 'archive_discovery', None)
    if not discovery:
        raise ValueError('content_provenance must run after page_discovery')
    text = discovery['article'].body_text()
    url = page.canonical_url
    raw_title = page.meta.get('search_title') or page.meta.get('title') or page.title
    title = normalize_text(raw_title) if isinstance(raw_title, str) else page.title
    source = Path(page.file.abs_src_path)
    record = {
        'document_id': document_id(url), 'url': url, 'title': title,
        'source_path': page.file.src_uri, 'text_sha256': digest(text),
        'source_sha256': sha256(source.read_bytes()).hexdigest(),
        'search_samples': search_samples(text), **_revision,
    }
    page.archive_provenance = record
    _documents[url] = record
    english = page.meta.get('lang') == 'en'
    use_label = 'Content use' if english else '콘텐츠 이용 안내'
    attrs = {'url': url, 'title': title, 'id': record['document_id'], 'version': record['text_sha256'][:12]}
    dataset = ' '.join(f'data-provenance-{key}="{escape(value, quote=True)}"' for key, value in attrs.items())
    guide = config['site_url'].rstrip('/') + '/guide/content-use/'
    footer = (
        f'<aside class="archive-provenance" data-search-exclude data-archive-provenance {dataset} aria-label="{use_label}">'
        f'<p><a href="{escape(guide, quote=True)}">{use_label}</a></p></aside>'
    )
    return html + footer


def on_post_page(output, page, config):
    record = getattr(page, 'archive_provenance', None)
    if record:
        head = ''.join(f'<meta name="archive:{name}" content="{escape(value, quote=True)}">\n' for name, value in (
            ('document-id', record['document_id']), ('text-sha256', record['text_sha256']),
            ('source-sha256', record['source_sha256']), ('commit', record.get('commit', ''))))
        output = output.replace('</head>', head + '</head>', 1)
    return output


def watermark_svg(original, relative, revision):
    if 'id="minseong-provenance-watermark"' in original:
        return original
    svg = ET.fromstring(original)
    values = [float(value) for value in re.split(r'[\s,]+', svg.attrib['viewBox'].strip())]
    x, y, width, height = values
    if width <= 0 or height <= 0:
        raise ValueError('Invalid artwork viewBox: ' + relative)
    asset_id = 'MSA-IMG-' + sha256(relative.encode()).hexdigest()[:12].upper()
    metadata = json.dumps({'asset_id': asset_id, 'publisher': '민성 한의학 아카이브',
        'url': 'https://wiki.minseong.co.kr/' + relative,
        'source_sha256': sha256(original.encode()).hexdigest(), **revision}, ensure_ascii=False)
    cx, cy = x + width/2, y + height*0.60
    mark = (
        '<g id="minseong-provenance-watermark" pointer-events="none" aria-hidden="true">'
        f'<text x="{cx:g}" y="{cy:g}" text-anchor="middle" '
        f'transform="rotate(-24 {cx:g} {cy:g})" fill="#506c62" opacity="0.22" '
        f'style="font:600 {min(22, width*0.029):g}px sans-serif;fill:#506c62">'
        'wiki.minseong.co.kr</text></g>'
        f'<metadata id="minseong-provenance">{escape(metadata)}</metadata>'
    )
    if '</svg>' not in original:
        raise ValueError('Missing SVG closing tag: ' + relative)
    return original.replace('</svg>', mark + '</svg>', 1)


def on_post_build(config):
    site = Path(config['site_dir'])
    artwork = []
    for folder in ARTWORK:
        for source in sorted((Path(config['docs_dir']) / 'assets' / folder).glob('*.svg')):
            relative = source.relative_to(config['docs_dir']).as_posix()
            target = site / relative
            original = source.read_text(encoding='utf-8')
            # The source and existing credits are preserved; only published copies change.
            target.parent.mkdir(parents=True, exist_ok=True)
            marked = watermark_svg(original, relative, _revision)
            target.write_text(marked, encoding='utf-8')
            artwork.append({'path': relative, 'source_sha256': sha256(original.encode()).hexdigest(),
                            'published_sha256': sha256(marked.encode()).hexdigest()})
    payload = {'schema_version': '1.0', 'publisher': '민성 한의학 아카이브',
        'base_url': config['site_url'], 'repository': REPOSITORY, **_revision,
        'normalization': 'SHA-256 over NFC article text with whitespace collapsed; navigation excluded.',
        'limits': 'Version references and similarity clues, not independent timestamps, ownership adjudication or visitor tracking. Third-party source rights remain separate.',
        'documents': [_documents[url] for url in sorted(_documents)], 'artwork': artwork}
    target = site / MANIFEST
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    # Small public search batches let scheduled checks rotate without downloading every article.
    searchable = [row for row in payload['documents'] if row['search_samples']]
    folder = site / 'assets/provenance/search-batches'
    folder.mkdir(parents=True, exist_ok=True)
    batches = []
    for start in range(0, len(searchable), 24):
        name = f'{start//24:03d}.json'
        rows = searchable[start:start+24]
        (folder/name).write_text(json.dumps({'documents':rows}, ensure_ascii=False) + '\n', encoding='utf-8')
        batches.append({'path':'assets/provenance/search-batches/'+name, 'documents':len(rows)})
    core_paths = {'conditions/low-back-pain.md','conditions/neck-pain.md','conditions/shoulder-pain.md',
        'conditions/dry-eye.md','conditions/eye-fatigue.md','conditions/facial-palsy.md',
        'conditions/dyspepsia.md','conditions/hair-loss.md','formulas/gyeongok-go.md'}
    core = [row for row in searchable if row['source_path'] in core_paths]
    (site/'assets/provenance/search-index.json').write_text(json.dumps({
        'schema_version':'1.0','batches':batches,'core_documents':core,
        'selection':'Choose a rotating batch using the current ISO week number modulo batch count; vary documents and phrases, and verify candidates manually.'
    }, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f'Content provenance: {len(_documents)} documents, {len(artwork)} watermarked SVGs')
